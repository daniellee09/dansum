export function buildUserPrompt(article: {
	title: string;
	description: string | null;
	content: string | null;
	sourceName: string;
}): string {
	const text = article.content || article.description || "";
	return `다음 뉴스 기사를 정리해주세요.

출처: ${article.sourceName}
제목: ${article.title}
본문:
${text.slice(0, MAX_BODY_CHARS)}`;
}

export interface SummaryResult {
	title: string;
	summary: string;
	sections: ArticleSection[];
	key_points: string[];
	category: string;
	keywords: string[];
}
